// Generates src/games/manifests.ts — a lightweight catalog of every game's
// `meta` so the dashboard can list games WITHOUT importing their (heavy) game
// code. Each game's code is then loaded lazily on play (see registry.ts).
//
// Run after adding or changing a game's meta:  npm run gen:manifests
import fs from "node:fs";
import path from "node:path";

const ROOT = "src/games";

const STREAM_ORDER = { physics: 0, chemistry: 1, biology: 2, "earth-space": 3 };
const gradeRank = (g) => (/^k/i.test(g) ? 0 : parseInt(g, 10) || 0);

const str = (block, name) => {
  const m = block.match(new RegExp(`${name}:\\s*"([^"]*)"`));
  return m ? m[1] : "";
};
const num = (block, name) => {
  const m = block.match(new RegExp(`${name}:\\s*(\\d+)`));
  return m ? Number(m[1]) : 0;
};

// Concept summaries from the curriculum become each game's "you discovered"
// takeaway — no per-game editing needed.
const SUMMARIES = {};
try {
  const cur = JSON.parse(fs.readFileSync("content/curriculum.json", "utf8"));
  for (const stream of cur.streams) for (const c of stream.concepts) SUMMARIES[c.id] = c.summary;
} catch {
  console.warn("⚠️  Could not read content/curriculum.json — takeaways will be empty");
}

const folders = fs
  .readdirSync(ROOT)
  .filter((f) => fs.existsSync(path.join(ROOT, f, "index.ts")));

const entries = [];
for (const folder of folders) {
  const src = fs.readFileSync(path.join(ROOT, folder, "index.ts"), "utf8");
  const metaMatch = src.match(/meta:\s*\{([\s\S]*?)\},\s*create/);
  if (!metaMatch) {
    console.warn(`⚠️  No meta found in ${folder}/index.ts — skipped`);
    continue;
  }
  const block = metaMatch[1];
  const id = str(block, "id");
  if (id !== folder) {
    // The lazy loader maps folder name -> game id, so they must match.
    console.warn(`⚠️  meta.id "${id}" does not match folder "${folder}"`);
  }
  const conceptId = str(block, "conceptId");
  entries.push({
    id,
    conceptId,
    title: str(block, "title"),
    stream: str(block, "stream"),
    gradeBand: str(block, "gradeBand"),
    emoji: str(block, "emoji"),
    blurb: str(block, "blurb"),
    mission: str(block, "mission"),
    estMinutes: num(block, "estMinutes"),
    takeaway: SUMMARIES[conceptId] || "",
  });
}

// Group by subject, then by grade — a friendlier browse order for kids.
entries.sort((a, b) => {
  const s = (STREAM_ORDER[a.stream] ?? 9) - (STREAM_ORDER[b.stream] ?? 9);
  if (s !== 0) return s;
  const g = gradeRank(a.gradeBand) - gradeRank(b.gradeBand);
  if (g !== 0) return g;
  return a.title.localeCompare(b.title);
});

const out = `import type { GameManifest } from "@sdk/types";

// AUTO-GENERATED by scripts/gen-manifests.mjs — do not edit by hand.
// Lightweight catalog metadata so the dashboard can list games without
// importing their (heavy) game code. Run \`npm run gen:manifests\` after
// adding or changing a game's meta.
export const GAME_MANIFESTS: GameManifest[] = ${JSON.stringify(entries, null, 2)};
`;

fs.writeFileSync(path.join(ROOT, "manifests.ts"), out);
console.log(`✅ Wrote ${ROOT}/manifests.ts with ${entries.length} games.`);
